CREATE TABLE sales(
	order_id VARCHAR(255),
    order_date VARCHAR(255),
    customer_name VARCHAR(255),
    product_name VARCHAR(255),
    category VARCHAR(255),
    profit VARCHAR(255),
    sales VARCHAR(255),
    order_date_new DATE,
    sales_new DECIMAL(10,2),
    profit_new DECIMAL(10,2)
    );
    